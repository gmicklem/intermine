package org.intermine.plugin.dbmodel

import org.gradle.api.Plugin
import org.gradle.api.Project

class BioSourceDBModelPlugin implements Plugin<Project>{

    BioSourceDBModelConfig config

    @Override
    void apply(Project project) {
        config = project.extensions.create('bioSourceDBModelConfig', BioSourceDBModelConfig)
        // Classpath of ModelMergerTask; the bio/sources build declares its dependencies.
        project.configurations.maybeCreate('mergeModel').canBeConsumed = false

        //only buildDB if there are tests to run
        if ((new File(project.projectDir.absolutePath + "/src/test")).exists()) {
            // lifecycle (kept): the tests need the bio-test database; it has no file output to wire.
            project.tasks.named('test').configure { dependsOn 'buildUnitTestDB' }
        }

        project.tasks.register('createTestPrioritiesFile') {
            description "Creates a blank genomic_priorities file for unit tests. When building, the mine's priority file will be used."
            // ordering only: it writes into processResources' output directory.
            mustRunAfter 'processResources'

            doLast {
                def file = new File(DBModelUtils.resourcesDir(project), "genomic_priorities.properties")
                file.parentFile.mkdirs()
                file.newWriter().withWriter { w ->
                    w << "# dummy file for unit tests"
                }
            }
        }
        project.tasks.named('test').configure {
            inputs.files(DBModelUtils.resource(project, 'createTestPrioritiesFile') { "genomic_priorities.properties" })
        }

        // One task copies genomic_model.xml from bio-model and merges this source's additions into it
        // (it used to be copyBioGenomicModel + copyGlobalAdditionsFile + mergeModels, which all ran
        // on every build). With the merged model as its declared output it is up to date when
        // nothing changed.
        project.tasks.register('mergeModels') {
            description "Merges the bio-source specific additions.xml into an intermine XML model"
            // If both run, merge after dbmodel's copyGenomicModel (unit tests), which would otherwise
            // overwrite the merged model with bio-model's.
            mustRunAfter 'copyGenomicModel'
            inputs.files({ project.configurations.getByName("bioModel") })
            inputs.files(project.configurations.getByName("mergeModel"))
            // the *_additions.xml files processResources puts into the resources directory
            inputs.files(project.files({
                project.fileTree(DBModelUtils.resourcesDir(project)) {
                    include '*_additions.xml'
                    exclude 'global_additions.xml'
                }
            }).builtBy('processResources'))
            inputs.files({ globalAdditionsSource(project) ?: [] })
            inputs.property('globalAdditionsFile', { config.globalAdditionsFile ?: '' })
            outputs.file({ new File(DBModelUtils.resourcesDir(project), "genomic_model.xml") })
            outputs.files({ globalAdditionsSource(project) ? [new File(DBModelUtils.resourcesDir(project), "global_additions.xml")] : [] })

            doLast {
                String buildResourcesMainDir = DBModelUtils.resourcesDir(project)
                String inputModelFilePath = buildResourcesMainDir + File.separator + "genomic_model.xml"

                // the genomic_model.xml file generated by bio-model (core.xml + genomic_additions + so.obo)
                DBModelUtils.copyFromArchive(project, project.configurations.getByName("bioModel").singleFile,
                        "genomic_model.xml", inputModelFilePath)
                // the extra global additions file (if specified), onto the classpath
                File globalAdditions = globalAdditionsSource(project)
                if (globalAdditions != null) {
                    project.copy {
                        from globalAdditions
                        into buildResourcesMainDir
                        rename { 'global_additions.xml' }
                    }
                }

                String bioSourceAdditionsFile = project.name.minus("bio-source-") + "_additions.xml"
                if ((new File(buildResourcesMainDir + File.separator + bioSourceAdditionsFile)).exists()) {
                    def ant = new AntBuilder()
                    ant.taskdef(name: "mergeBioSourceModel", classname: "org.intermine.task.ModelMergerTask") {
                        classpath {
                            pathelement(path: project.configurations.mergeModel.asPath)
                            dirset(dir: project.buildDir.absolutePath)
                        }
                    }
                    String extraAdditionsFile = config.globalAdditionsFile
                    if (extraAdditionsFile != null) {
                        ant.mergeBioSourceModel(inputModelFile: inputModelFilePath, additionsFile: "global_additions.xml",
                                outputFile: inputModelFilePath)
                    }
                    ant.mergeBioSourceModel(inputModelFile: inputModelFilePath, additionsFile: bioSourceAdditionsFile,
                            outputFile: inputModelFilePath)
                }
            }
        }
    }

    /** The configured global additions file under the root project, or null if there is none. */
    File globalAdditionsSource(Project project) {
        File file = new File(project.rootDir.absolutePath + "/" + config.globalAdditionsFile)
        file.exists() ? file : null
    }
}
